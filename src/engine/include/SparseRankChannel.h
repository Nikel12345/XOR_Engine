#pragma once
#include <cstdint>
#include <vector>

class BufferManager;
struct UploadTask;

// ───────────────────────── Разреженный по строкам канал ─────────────────────────
// Данные есть у малой доли строк домена, и держать под них полноразмерное поле — значит платить
// его ширину за значение «ничего нет». Вместо этого на строку остаётся один бит присутствия, а
// сами данные лежат КОМПАКТНО, по одному элементу на носителя; адрес элемента даёт rank — число
// носителей до этой строки, считаемое за O(1) без поиска.
//
// Здесь — только rank-часть, общая для всех таких каналов (UI-текст, состояния вариантов текстур).
// Что лежит ПО rank'у, каждый канал объявляет сам: у текста это {offset,count} в пул глифов,
// у состояний — смещение ячеек. Шейдерная половина — shaders_code/sparse_rank.hlsli.
//
// РАСКЛАДКА СЛОВА обязана совпадать с шейдерной (там макрос SPARSE_CHANNEL объявляет
// StructuredBuffer<uint2>): x = биты присутствия 32 строк, y = число носителей ДО этого слова.
//
// bits и base лежат В ОДНОМ буфере, а не в двух: по отдельности они не бывают валидны (base —
// бегущая сумма по тем же битам), и залить одно без другого значит получить молча неправильные
// rank; раздельные буферы это разрешают, слитый — нет. Заодно шейдер берёт пару одной загрузкой
// из одной кэш-линии, а в общих прологах на один бинд меньше — каждый буфер там обязана биндить
// КАЖДАЯ sp, включившая пролог.
struct SparseRankWord {
	uint32_t bits;
	uint32_t base;
};

inline uint32_t SparseRankWordCount(uint32_t rows) { return (rows + 31u) / 32u; }
inline uint32_t SparseRankBytes(uint32_t rows) {
	return SparseRankWordCount(rows) * static_cast<uint32_t>(sizeof(SparseRankWord));
}

// Раскладывает строки носителей (hit_rows, ОБЯЗАНЫ идти по возрастанию) в слова канала и заливает
// их пачками. Полного массива слов на CPU не держит: слово без носителей — это ровно {0, сколько
// их было до него}, поэтому поток строится на лету. Домен задаёт rows: слов будет столько же,
// сколько насчитает SparseRankWordCount, и заливка совпадёт с размером от SparseRankBytes.
void StoreSparseRank(BufferManager* bm, UploadTask* task, uint32_t rows,
                     const std::vector<uint32_t>& hit_rows);
