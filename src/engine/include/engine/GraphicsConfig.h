#pragma once
#include <algorithm>
#include <cmath>
#include <cstdint>
#include "Utils.h"

// Настройки графики: ЖЁСТКИЙ набор полей под размеры экранных таргетов. Намеренно НЕ тип
// ParamsSpecRegistry (как параметры материала или состояние прохода) — на четыре поля схема,
// генерируемый инспектор и round-trip по именам не окупаются.
//
// ВЛАДЕНИЕ И ПОТОК. Объект живёт на куче у Engine, указатель стабилен всю его жизнь: читатели
// держат указатель, писатель правит поля на месте.
// ПИШЕТ его только render-поток — и гейт размеров, и панель редактора (UI_ImGui::Iterate) исполняются
// внутри Engine::RenderFunc, поэтому писателя между сравнением и применением не существует.
// ЧИТАЕТ его ещё и sim-поток: Engine::GetWidth/GetHeight выводят внутреннее разрешение прямо отсюда.
// Синхронизации нет намеренно — это набор скаляров, и худшее, что даст рваное чтение, это неверный
// размер на один кадр (гейт сравнивает снимок и на следующем кадре сойдётся сам).
// Если настройки появятся в ИГРОВОМ UI, писателем станет sim-поток — вот тогда значения придётся
// публиковать командой, а в замыкания ресайза отдавать СНИМОК вместо живого указателя, иначе
// применится не то, что сравнил гейт.
struct GraphicsConfig {
    // База внутреннего разрешения — размер scene_hdr и всего, что живёт в его разрешении
    // (emission/ambient/depth). 0 = следовать за размером назначения (по умолчанию render == окно).
    uint32_t render_w = 0;
    uint32_t render_h = 0;

    // Частота сэмплирования сцены относительно вывода, поверх базы выше. Это и есть сглаживание:
    // 2.0 = SSAA 2x (рендерим вчетверо больше пикселей, present-блит усредняет их вниз), меньше
    // единицы = масштабирование ради fps. Эффектов НЕ касается — тем лишние сэмплы не нужны.
    // Множителем, а не абсолютом, чтобы настройка переживала ресайз окна: с абсолютным render_w
    // растянутое окно молча превратило бы «сглаживание 2x» в 1.5x, а потом и в даунскейл.
    float render_scale = 1.0f;

    // Общий множитель на ВСЕ экранные таргеты: сброс качества целиком (слабое железо, окно-превью).
    // От render_scale отличается тем, что задевает и эффекты: тот меняет частоту сэмплирования
    // сцены, этот — сколько всего пикселей движок согласен посчитать.
    float global_scale = 1.0f;

    // Доли эффект-домена. Эффект-домен = min(render, назначение), и минимум здесь обязателен,
    // потому что render_scale работает в обе стороны: выше render информации нет (её никто не
    // посчитал), выше назначения её некуда показать.
    float ssao_scale  = 0.5f;

    // Опускать ниже 0.5 можно, но с оговоркой. Футпринт ядра bloom_prefilter отношение сокращения
    // отслеживает (шаг взят в текселях приёмника), так что кадр не «съезжает». Но тапов остаётся
    // 13 при любом отношении: на 2:1 они накрывают свой блок с запасом, на 4:1 уже с прорехами.
    // Заметно это будет на том же, на чём всегда, — на мелком ярком. Полноценный ответ — не число
    // здесь, а двухступенчатое сокращение (полный → половина → четверть).
    // У ssao_scale такого ограничения нет вовсе: SSAO не сокращает изображение, а считает своё
    // значение с нуля, сэмплируя глубину в МИРОВОМ радиусе.
    float bloom_scale = 0.5f;

    bool operator==(const GraphicsConfig&) const = default;
};

// Округление ВВЕРХ, а не вниз: при нечётной стороне «вниз» потеряло бы крайний столбец кадра.
// Ноль, отрицательное и NaN сводятся к 1 — таргета нулевого размера не бывает.
inline uint32_t GfxScaleDim(uint32_t v, float scale)
{
    const float f = std::ceil(static_cast<float>(v) * scale);
    if (!(f >= 1.0f)) return 1;
    return safe_f_u32(f);
}

// База внутреннего домена: либо пин из конфига, либо размер назначения. Ещё без масштабов.
inline uint32_t GfxRenderBaseW(const GraphicsConfig& c, uint32_t out_w) { return c.render_w ? c.render_w : out_w; }
inline uint32_t GfxRenderBaseH(const GraphicsConfig& c, uint32_t out_h) { return c.render_h ? c.render_h : out_h; }

// База эффектного домена: min(render, назначение). render здесь взят С render_scale, но БЕЗ
// global_scale — тот применяется в самом конце и одинаково ко всем таргетам, включая эффектные,
// поэтому вносить его в минимум значило бы учесть дважды.
inline uint32_t GfxEffectBaseW(const GraphicsConfig& c, uint32_t out_w)
{ return std::min(GfxScaleDim(GfxRenderBaseW(c, out_w), c.render_scale), out_w); }
inline uint32_t GfxEffectBaseH(const GraphicsConfig& c, uint32_t out_h)
{ return std::min(GfxScaleDim(GfxRenderBaseH(c, out_h), c.render_scale), out_h); }

// Конечные размеры таргетов. Вывод обязан идти ОДНОЙ функцией у всех потребителей — замыканий
// ресайза, первичного создания таргетов и геттеров внутреннего разрешения: разойдись они хоть на
// пиксель, гейт сравнения не сойдётся никогда и таргеты будут пересоздаваться каждый кадр.
inline void GfxRenderTarget(const GraphicsConfig& c, uint32_t out_w, uint32_t out_h, uint32_t& w, uint32_t& h)
{
    w = GfxScaleDim(GfxRenderBaseW(c, out_w), c.render_scale * c.global_scale);
    h = GfxScaleDim(GfxRenderBaseH(c, out_h), c.render_scale * c.global_scale);
}
inline void GfxEffectTarget(const GraphicsConfig& c, uint32_t out_w, uint32_t out_h, float scale, uint32_t& w, uint32_t& h)
{
    w = GfxScaleDim(GfxEffectBaseW(c, out_w), scale * c.global_scale);
    h = GfxScaleDim(GfxEffectBaseH(c, out_h), scale * c.global_scale);
}
