#pragma once
#include "GpuQueues.h"

// Владелец очередей GPU и единственная точка, где решается, на какую из них поедет лейн.
//
// Лист, как и прочие менеджеры (см. CLAUDE.md): не держит указателей на другие менеджеры и не
// зовёт их. Наружу отдаёт ЗНАЧЕНИЯ (UploadQueue/RenderQueue размером с указатель) — их не
// нужно хранить в полях, берутся заново там, где нужны.
//
// ЧЕМ ОКАЗЫВАЕТСЯ ОЧЕРЕДЬ — решает SDL, и вызывающего это не касается. Роль (заливка/вычисление/
// рендер) переводится в семью очередей один раз, при создании устройства, и роль без своей семьи
// получает ближайшую БОЛЕЕ ШИРОКУЮ: заливка без выделенной DMA-семьи уходит на вычислительную,
// а не сразу на графическую, потому что это всё ещё другой аппаратный движок. Ни здесь, ни у
// вызывающего ветки «а есть ли такая очередь» нет и не должно быть — в этом весь смысл.
//
// Fallback штатный и постоянный, а не временный: у Metal один MTLCommandQueue by design, у
// D3D12 один DIRECT-список, и на таком железе все три обёртки будут смотреть в одну очередь.
// Код, написанный поверх этих типов, от этого не меняется ни строкой — меняется только степень
// перекрытия работы.
class QueueManager {
public:
    explicit QueueManager(SDL_GPUDevice* device);

    UploadQueue  GetUploadQueue() const;
    ComputeQueue GetComputeQueue() const;
    RenderQueue  GetRenderQueue() const;

    SDL_GPUDevice* GetDevice() const { return device_; }

private:
    SDL_GPUDevice* device_ = nullptr;
};
