#pragma once
#include <cstdint>
class EngineContext;

// Дефолтные ресурсы движка, у которых есть АЛЬТЕРНАТИВНЫЕ наборы. Сейчас — фон сцены:
// классический скайбокс (env-кубмапа) или фрактал (Мандельброт). Всё создаётся кодом и
// dont_save (в файлы сцены не идёт). Энтити фона создаёт LoadScene (производная сущность,
// GeneratedComponent) и ссылается на материал ПО ИМЕНИ "_skybox" — поэтому оба набора
// создают материал под этим именем, различается только программа внутри. Выбор набора —
// Engine::InitDefaultResources (2 вызова под if).
namespace DefaultResourcesNamespace
{
    // Классический скайбокс: unlit-фон по env-кубмапе (глобалка MAIN_PASS, слот 1).
    void SetDefaultSkyboxResources(EngineContext* ctx);

    // Альтернативный фон: 3D-губка Менгера рэймарчем тем же скайбокс-путём (куб вокруг
    // камеры, _skybox_vs, v_dir — направление луча пикселя; origin — позиция камеры из view).
    // У губки, в отличие от Мандельброта, есть ЗАМКНУТАЯ функция расстояния (IFS-фолдинг) —
    // референс-орбита/перетурбация не нужны, буферов кроме камеры нет (орбитный буфер и его
    // апдейтер удалены вместе с 2D-версией). См. fractal/menger.frag.hlsl.
    void SetFractalSkyboxResources(EngineContext* ctx);

    // Ручное управление масштабом (клавиши I/K игры): delta = +1 — на уровень глубже (кадр
    // ×3 мельче: скорость и потолок детализации следуют за кадром), −1 — наружу. Сам ребейз
    // камеру не двигает (та же мировая точка, только единицы) — «зум» проявляется через
    // скорость полёта и детализацию. Боковой выход из ячейки перепривязывается автоматически
    // БЕЗ смены масштаба (подъём+спуск в соседа). Вызывать с sim-потока (апдейт игры).
    void FractalScaleStep(int delta);

    // Push-константы фрактального фона (fragment слот 0 → b0, space3; раскладка = cbuffer
    // FractalParams в mandelbrot.frag.hlsl). ВАЖНО: тело MAIN_PASS передаёт в push_func
    // nullptr вместо данных (RenderPassStandardBody(..., nullptr)), поэтому биндить надо
    // НАПРЯМУЮ полем sp->push_func лямбдой, игнорирующей raw, — BindPushConstants<T>
    // разыменовывает raw и на программах main-пасса падал бы.
    struct alignas(16) FractalPushData {
        float    time      = 0.0f;   // медленное вращение источника света
        uint32_t max_steps = 200;    // потолок шагов рэймарча (sphere tracing)
        float    _pad0     = 0.0f;
        float    _pad1     = 0.0f;
    };
}
