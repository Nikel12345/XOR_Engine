// Одна sp материала ВМЕСТЕ с данными, которые материал даёт ИМЕННО ЕЙ. Ячейка, а не две
// параллельные коллекции (список имён + общий блоб): у списка и данных один владелец, поэтому
// разъехаться им негде — добавили sp, её данные заводятся тут же; убрали — уходят вместе с ней.
struct SpBinding {
    ShaderName sp;   // ссылка ПО ИМЕНИ на реестр ShaderManager (резолв — на сборке батча)

    // Непрозрачный блоб per-sp факторов (baseColor, metallic, alpha, ...). Раскладку задаёт автор
    // шейдера (его cbuffer MaterialBlock); движок видит байты и пушит их как есть, НЕ проверяя.
    // ПУСТО (nullptr или блоб нулевого размера) = «параметров нет»: sp их не читает
    // (ShadowCaster, Wireframe) — пушить нечего, и в ключ texture-батча она их не вносит,
    // поэтому такие проходы материалы не различают вовсе.
    //
    // В КУЧЕ, а не значением: ячейки лежат в векторе, который мутируется в рантайме
    // (Add/RemoveMaterialShader из редактора), а на АДРЕС блоба ссылаются дерево батчей
    // (TextureBatchData::params) и слепок рендера — он обязан пережить реаллокацию вектора.
    // Мутация самих БАЙТ адрес не трогает, поэтому твики в инспекторе по-прежнему идут
    // in-place, без перестройки дерева.
    std::unique_ptr<std::vector<uint8_t>> params;

    // ИМЯ типа params в реестре ParamsSpecRegistry (см. ParamsSpec.h) — тег ТОЛЬКО для тулинга:
    // по нему инспектор находит схему полей, а Save/LoadScene пишет и читает их по-именно.
    // Рендер тег не читает (для него params — непрозрачные байты). Строка, а не enum, ради
    // открытой регистрации: тип, объявленный в коде игры, называет себя сам.
    // ИНВАРИАНТ: params_type пусто ⟺ блоб пуст (держат Apply/ClearMaterialParams).
    std::string params_type;
};

struct Material {
    // Пользовательский ресурс ссылается на другой ТОЛЬКО по имени (правило редактора): не
    // указатель/weak_ptr, а имя, резолвится лениво в BatchBuilder на сборке батчей (TextureManager
    // по имени → TextureHandle). Промах (текстура удалена/переименована/ещё не создана) → nullptr →
    // dummy в батче. В отличие от weak_ptr, имя ПЕРЕЖИВАЕТ delete+recreate под тем же именем: ссылка
    // перепривязывается на новый хэндл при следующей пересборке, без ручной инвалидации.
    //
    // Текстуры — ОБЩИЕ для всех sp материала и ключуются РОЛЬЮ: две sp, требующие Albedo, берут
    // одну и ту же запись (правка под одной видна под другой). Форму слотов в инспекторе диктует
    // required_slots КАЖДОЙ sp, а значение живёт здесь. Этим текстуры и отличаются от params:
    // у роли есть общее имя, у блоба — только его шейдер.
    //
    // Слот держит СПИСОК текстур: [0] — то, что рисуется по умолчанию, дальше ВАРИАНТЫ,
    // переключаемые состоянием НА СУЩНОСТИ (MaterialRef::states). Пустой вектор = слота нет.
    // Слот с >1 текстурой называется ВАРИАТИВНЫМ и получает ячейку в секции состояний.
    // std::map, а не unordered_map: порядок ролей задаёт нумерацию ячеек, и он обязан быть
    // детерминированным — его независимо считают BatchBuilder (для пуша) и модуль заливки
    // состояний (для записи секции). Разъезд этих двух нумераций не крашится и не логируется,
    // объекты просто показывают чужие варианты.
    std::map<TextureSlotRole, std::vector<TextureName>> textures;

    // Проходы материала: sp + её собственные данные (см. SpBinding). Порядок = порядок объявления.
    std::vector<SpBinding> shader_programs;

    // Кладбище блобов снятых sp. Освободить блоб может ТОЛЬКО смерть материала: на его адрес
    // смотрят дерево батчей (TextureBatchData::params) и слепок рендера, а тот живёт ещё
    // несколько кадров после правки — удаление sh-программы из редактора не имеет права
    // дёрнуть free под рендер-потоком. Поэтому RemoveMaterialShader переселяет блоб сюда,
    // а не роняет его. Материалы сносятся только в LoadScene, под scene_swap_mutex.
    std::vector<std::unique_ptr<std::vector<uint8_t>>> retired_params;

    // Не писать в materials.json при SaveScene (кодовая инфраструктура — напр. debug_collider,
    // используемый только генератором debug-рамок). UI/пересоздание → false («тронул = сохраняемый»).
    bool dont_save = false;

    // Линейный поиск: sp у материала единицы, все вызовы холодные (сборка батча, редактор, загрузка).
    SpBinding* FindBinding(const ShaderName& sp_name) {
        for (SpBinding& b : shader_programs) if (b.sp == sp_name) return &b;
        return nullptr;
    }
    const SpBinding* FindBinding(const ShaderName& sp_name) const {
        for (const SpBinding& b : shader_programs) if (b.sp == sp_name) return &b;
        return nullptr;
    }
};
