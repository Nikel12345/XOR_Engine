#pragma once
#include <vector>
#include <cstdint>

// Одномерный аллокатор диапазонов В ЭЛЕМЕНТАХ — разметка буферов пула геометрии.
// Аналог AtlasPacker для текстур, но проще по существу: там прямоугольники и свободное место
// восстанавливается пересборкой слоя из выживших, здесь отрезки — соседи сливаются точно и на
// месте, поэтому список правится инкрементально и пакетное освобождение ради скорости не нужно.
//
// Живёт ОТДЕЛЬНО от GeometryPool намеренно: пул описывает раскладку и буферы, а размечать их
// никто не обязан — стримы можно писать целиком compute-шейдером, ни одной модели не заведя
// (так делает sandbox/QueueThreadingProbe). Ровно та же необязательность, что у AtlasPacker.
//
// Ничего не знает про GPU, фенсы и кадры: отложенность освобождения — забота владельца
// (ModelManager штампует диапазоны и зовёт Free, когда штамп созрел).
class RangeAllocator
{
public:
    struct Range {
        uint32_t first = 0;
        uint32_t count = 0;   // 0 = пусто/не выделено
    };

    // First-fit ПО АДРЕСУ (список отсортирован): фрагментирует меньше best-fit на длинных сессиях.
    // Подходящей дыры нет — растём с вершины, то есть ведём себя как прежняя дозапись в конец.
    Range Allocate(uint32_t count);
    // Возврат со слиянием соседей. Диапазон обязан быть выданным этим же аллокатором и ещё не
    // освобождённым — двойной возврат склеит чужое место в одну дыру.
    void  Free(Range r);

    // Вершина занятого: точка дозаписи при промахе и высокая вода для RESIZE_AND_COPY.
    uint32_t Top() const { return top_; }
    void Reset();

    // Диагностика (лог/UI): сколько дыр и сколько в них суммарно элементов.
    size_t   FreeBlocks() const { return free_.size(); }
    uint32_t FreeTotal()  const;

private:
    // ИНВАРИАНТ: отсортирован по first, соседние блоки слиты, пустых нет. На нём держится и
    // слияние (смотрим только двух соседей), и опускание вершины.
    std::vector<Range> free_;
    uint32_t top_ = 0;
};
