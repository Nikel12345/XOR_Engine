#pragma once
#include <cstdint>
class EngineContext;

// Фрактальный фон (3D-губка Менгера) — код ИГРЫ, не движка. Рисуется скайбокс-путём: куб вокруг
// камеры + skybox_vs (v_dir — направление луча пикселя, глубина ровно 1.0), фрагментник — рэймарч
// по замкнутой функции расстояния губки. Ресурсы рендера (модель/шейдеры/sp/материал) — ресурсы
// СЦЕНЫ (saved_scene_fractal), энтити фона — в её scene.json. Здесь — несериализуемая часть:
// буфер кадра фрактала с апдейтером и позиция/масштаб камеры во фрактале.
//
// МОДЕЛЬ ПОЗИЦИИ/МАСШТАБА. Камера движка — чистый АККУМУЛЯТОР сдвига в игровых юнитах
// (каждый тик обнуляется; скорость от масштаба НЕ зависит). Позиция во фрактале хранится
// трёхчастно, чтобы точность не зависела от глубины:
//   g_addr  : целочисленный адрес якорной ячейки — цифры спуска по основанию 3 (root-first,
//             по осям). Точная арифметика: боковой перелёт в соседнюю ячейку = перенос разряда,
//             любой длины за один тик, без потери точности. Глубина не ограничена точностью
//             (потолок MAX_DEPTH — только здравый смысл);
//   g_local : double-позиция ВНУТРИ якорной ячейки (юниты ячейки, всегда ~O(1) — младшие биты
//             double всегда при деле, дельта не поглощается ни на какой глубине);
//   g_sigma : дробная часть масштаба σ ∈ [1,3); полный масштаб s = σ·3^-d, d = глубина адреса.
// Кадр шейдера каждый тик выводится из этой тройки; смена якоря — точная замена координат
// (×3∓D в double + пуш/поп цифры), непрерывность на экране сшивают σ-масштабируемые туман/tFar
// (в буфере кадра) и внесение сдвига (игровая дельта × 0.05·σ → юниты ячейки).
//
// МАСШТАБ — АВТОМАТИЧЕСКИЙ: σ следует за расстоянием до поверхности (CPU-зеркало DE губки,
// сглаживание в лог-пространстве). Мировая скорость = дельта·0.05·s ∝ дистанции: подлёт сам
// замедляется и раскрывает детализацию — «зум» = лететь к грани, врезаться невозможно
// (приём фрактальных леталок: Marble Marcher, Fragmentarium). I/K — ручной сдвиг окна поверх.
namespace FractalBackground
{
    // Имя буфера кадра. На него по имени ссылается sp "Fractal" (fs_buffers в shaders.json
    // сцены) — поэтому буфер ДОЛЖЕН существовать до LoadScene (резолв имён буферов идёт по
    // уже созданным, см. ResolveBufferName в Engine_Scene).
    inline constexpr const char* FRACTAL_FRAME_BUFFER = "_FractalFrameBuffer";

    // Буфер кадра фрактала + его пер-кадровый апдейтер (внесение сдвига камеры, ренормализация
    // масштаба, переносы адреса, публикация кадра). Звать один раз в MainInit ДО LoadScene.
    void CreateFractalFrameResources(EngineContext* ctx);

    // Ручной СДВИГ окна масштаба относительно авто (удержание I/K): delta_levels — доля
    // уровня за вызов, множитель *= 3^-delta (+ = «я мельче»: окно детализации/скорость
    // глубже авто-цели; − = крупнее). Нейтраль 1, диапазон ±6 уровней. Сам масштаб следует
    // за расстоянием до поверхности автоматически. Вызывать с sim-потока.
    void FractalScaleStep(float delta_levels);

    // Push-константы фрактального фона (fragment слот 0 → b0, space3; раскладка = cbuffer
    // FractalParams в menger.frag.hlsl). ВАЖНО: тело MAIN_PASS передаёт в push_func nullptr
    // вместо данных (RenderPassStandardBody(..., nullptr)), поэтому биндить надо НАПРЯМУЮ
    // полем sp->push_func лямбдой, игнорирующей raw, — BindPushConstants<T> разыменовывает
    // raw и на программах main-пасса падал бы.
    struct alignas(16) FractalPushData {
        float    time      = 0.0f;   // медленное вращение источника света
        // Потолок шагов рэймарча. С over-relaxation (ω=1.6) и «потолок = хит-кандидат»
        // (см. марш в menger.frag.hlsl) 128 достаёт дальше прежних 200 простых шагов,
        // а худшие (скользящие вдоль стен) пиксели дешевле на ~треть.
        uint32_t max_steps = 128;
        float    _pad0     = 0.0f;
        float    _pad1     = 0.0f;
    };
}
